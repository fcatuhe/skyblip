#!/usr/bin/env python3
"""Generate the ADS-L or ADS-B test report, clause by clause.

    python3 scripts/conformance.py adsl
    python3 scripts/conformance.py adsb

The ADS-L report follows the specification and adds EN 300 220 and the stack's own tests.
The ADS-B report follows the DO-260B receive-side clause listing. The generator runs the
selected suite twice through doctest's JUnit reporter. The normal run must pass. The second
run uses --no-skip to read the failure message that explains each skip.
"""
import argparse
import dataclasses
import os
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
from collections import Counter, defaultdict
from itertools import chain

import behavior_index
import check_clauses

ROOT = check_clauses.ROOT
ADSL = next(s for s in check_clauses.STANDARDS if s.title.startswith("ADS-L"))
DO260B = next(s for s in check_clauses.STANDARDS if s.title.startswith("DO-260B"))
FIRMWARE = os.path.join(ROOT, "firmware")
TEST_BINARY = os.path.join(FIRMWARE, "build", "skyblip_tests")
EN300220_CLAUSES = os.path.join(FIRMWARE, "test", "en300220", "clauses.txt")

ADSL_UNIT = "protocols/adsl/test/"
ADSL_COMPONENT = ADSL_UNIT + "conformance/"
ADSL_DEVICE = "test/adsl/"
EN300220 = "test/en300220/"
ADSB_COMPONENT = "protocols/adsb/test/conformance/"
ADSB_DEVICE = "test/adsb/"
SOURCE_ROOTS = {
    "adsl": (ADSL_UNIT, ADSL_DEVICE, EN300220),
    "adsb": (ADSB_COMPONENT, ADSB_DEVICE),
}

APPENDIX = ADSL.unnumbered[0]
PERFORMANCE_APPENDIX = "APPENDIX - PERFORMANCE INFORMATION"
SECTION = re.compile(r"^## ((?:SUBPART|APPENDIX)\b.*)$")
CLAUSE_HEADING = re.compile(rf"^#+\s+({ADSL.clause})\s+(.*)$")
EN300220_CLAUSE = re.compile(r"^(EN 300 220-\d \d+(?:\.\d+)*) (.*)$")
SEPARATOR = behavior_index.SUBJECT_SEPARATOR

ADSL_HEADER = """# ADS-L conformance

skyBlip's ADS-L implementation {version}, read against {specification} clause by clause by the host test suite. Each of the specification's {clauses} clause headings is below, in the document's order, with the cases that read it: {passed} pass and {skipped} are skipped ({kinds}).

Each claim names the file that checks it, under `firmware/`. A file under `protocols/adsl/test/conformance/` belongs to the component, which builds and passes on its own and goes with any copy of the stack (`firmware/protocols/README.md`, Taking a stack into another project). A file under `test/adsl/` needs skyBlip around the stack, because it checks skyBlip's choices, which a copy replaces with its own. A skipped case is a clause this device makes no claim on, and says why: prose, paperwork, optional, not implemented or unmeasured (`firmware/test/adsl/README.md`). Quoted prose is the comment the case carries.

Generated by `scripts/conformance.py adsl` from the run itself, and diffed in CI. Do not edit: rename the test case, or rewrite the comment it carries.
"""

ADSB_HEADER = """# ADS-B conformance

The host test suite reads skyBlip's ADS-B implementation {version} against RTCA DO-260B draft 4.2 (1090-WP30-18). This report covers the {clauses} receive-side clauses listed in [`firmware/test/adsb/clauses.txt`](../firmware/test/adsb/clauses.txt). The suite passed {passed} cases and skipped {skipped} ({kinds}).

Each case names its file under `firmware/`. The cases under `protocols/adsb/test/conformance/` exercise the standalone decoder and report assembly. The device cases under `test/adsb/` test Bravo's driver against an LR2021 radio model, not physical radio hardware. Skipped cases give the reason they carry no claim. See [`firmware/test/adsb/README.md`](../firmware/test/adsb/README.md) for the receiver's scope and known gaps. Quoted prose comes from the test case's comment.

Generated by `scripts/conformance.py adsb` from the test run. CI checks that this report matches the suite. Change the test name or comment to update the report.
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("protocol", choices=SOURCE_ROOTS)
    protocol = parser.parse_args().protocol
    output = os.path.join("docs", f"{protocol.upper()}_CONFORMANCE.md")
    try:
        passed, skipped = run_suite(SOURCE_ROOTS[protocol])
        paths = {path for path, _ in passed} | {path for path, _, _ in skipped}
        prose = {path: behavior_index.read_prose(path)[1] for path in paths}
        version = read(os.path.join(FIRMWARE, "protocols", protocol, "version.h"))
        if protocol == "adsl":
            document = render_adsl(passed, skipped, prose, read(ADSL.spec),
                                   read(EN300220_CLAUSES), version)
        else:
            clauses = do260b_clauses(DO260B.listing)
            document = render_adsb(passed, skipped, prose, clauses, version)
    except (ValueError, ET.ParseError, OSError, subprocess.CalledProcessError) as error:
        report(str(error))
        return 1
    with open(os.path.join(ROOT, output), "w", encoding="utf-8") as out:
        out.write(document)
    report(f"{len(passed)} cases passed and {len(skipped)} skipped -> {output}")
    return 0


def run_suite(source_roots):
    if not os.path.exists(TEST_BINARY):
        raise ValueError(f"no test binary at {os.path.relpath(TEST_BINARY, ROOT)}: "
                         "run `make -C firmware test` first")
    source_files = ",".join(f"*{root}*" for root in source_roots)
    return classify_runs(junit(source_files), junit(source_files, "--no-skip"))


def classify_runs(normal, no_skip):
    ran = indexed_cases(normal, "normal run")
    all_cases = indexed_cases(no_skip, "--no-skip run")
    failures = [f"{path}: {name}: {message}" for (path, name), message in ran.items()
                if message is not None]
    if failures:
        raise ValueError("the normal suite run contains failures:\n" + "\n".join(failures))

    skipped = []
    for (path, name), failure in all_cases.items():
        if (path, name) not in ran:
            if failure is None:
                raise ValueError(f"a skipped case passes with --no-skip: {path}: {name}")
            if check_clauses.kind_of(failure) is None:
                raise ValueError(f"a skipped case has no recognized reason: {path}: {name}: {failure}")
            skipped.append((path, name, failure))
    return list(ran), skipped


def indexed_cases(cases, run):
    indexed = {}
    for path, name, failure in cases:
        key = (path, name)
        if key in indexed:
            raise ValueError(f"duplicate case in {run}: {path}: {name}")
        indexed[key] = failure
    return indexed


# INFO: fc 19nov26 scenario cases open scenarios/*.json by relative path, so this runs in firmware/
def junit(source_files, *extra):
    run = subprocess.run(
        [TEST_BINARY, "--reporters=junit", f"--source-file={source_files}", "--no-exitcode", *extra],
        cwd=FIRMWARE, stdout=subprocess.PIPE, text=True, encoding="utf-8", check=True,
    )
    return junit_cases(run.stdout)


def junit_cases(xml):
    cases = []
    for case in ET.fromstring(xml).iter("testcase"):
        path, name = case.get("classname"), case.get("name")
        error = case.find("error")
        if error is not None:
            raise ValueError(f"the suite reported an error: {path}: {name}: {error.get('message')}")
        failures = [failure.get("message", "") for failure in case.findall("failure")]
        message = next((failure for failure in failures if check_clauses.kind_of(failure)),
                       failures[0] if failures else None)
        cases.append((path, name, message))
    return cases


def render_adsl(passed, skipped, prose, spec, en300220_clauses, version_h):
    verify_case_paths(chain(passed, skipped), SOURCE_ROOTS["adsl"])
    adsl = matching_cases(passed, ADSL_COMPONENT, ADSL_DEVICE)
    adsl_skipped = matching_cases(skipped, ADSL_COMPONENT, ADSL_DEVICE)
    sections = spec_sections(spec)
    clauses = {clause for _, entries in sections for clause, _ in entries}
    by_clause = clause_claims(adsl, adsl_skipped, prose, ADSL_COMPONENT)
    appendix = {APPENDIX} if any(section == PERFORMANCE_APPENDIX for section, _ in sections) else ()
    verify_clauses(by_clause, clauses, optional=appendix)

    lines = [ADSL_HEADER.format(
        version=quoted(version_h, "kVersion"),
        specification=quoted(version_h, "kSpecification"),
        clauses=len(clauses),
        passed=len(adsl),
        skipped=len(adsl_skipped),
        kinds=kind_counts(message for _, _, message in adsl_skipped),
    )]
    for section, entries in sections:
        lines.append(f"## {section}\n")
        for clause, titles in entries:
            lines.append(f"### {clause} {titles[0]}\n")
            for title in titles[1:]:
                lines.append(f"Issue 2 gives the same number to {title}, "
                             "so the cases of both clauses are here.\n")
            lines.extend(by_clause[clause])
            lines.append("")
        if section == PERFORMANCE_APPENDIX:
            lines.append(f"### {APPENDIX} Performance information\n")
            lines.extend(by_clause.get(APPENDIX, []))
            lines.append("")

    en_entries = en300220_entries(en300220_clauses)
    en_claims = clause_claims(matching_cases(passed, EN300220), matching_cases(skipped, EN300220),
                              prose, EN300220)
    verify_clauses(en_claims, {clause for clause, _ in en_entries})
    lines.append("## EN 300 220, the standard D.3 names\n")
    for clause, title in en_entries:
        lines.append(f"### {clause} {title}\n")
        lines.extend(en_claims[clause])
        lines.append("")

    lines.append("## The stack's own tests\n")
    lines.append("What the component checks beyond the clauses, by file: the packet over a "
                 "bit-error channel, the uplink's code, the media access branch by branch and "
                 "the version.\n")
    unit, unit_skips = defaultdict(list), defaultdict(list)
    for path, name in matching_cases(passed, ADSL_UNIT):
        if not path.startswith(ADSL_COMPONENT):
            unit[path].append(name)
    for path, name, message in matching_cases(skipped, ADSL_UNIT):
        if not path.startswith(ADSL_COMPONENT):
            unit_skips[path].append(skipped_line(path, name, message))
    for path in sorted(unit.keys() | unit_skips.keys()):
        lines.append(f"### {path}\n")
        lines.extend(behavior_index.render_subjects(unit[path], prose[path]))
        if unit_skips[path]:
            lines.extend(unit_skips[path])
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_adsb(passed, skipped, prose, clauses, version_h):
    verify_case_paths(chain(passed, skipped), SOURCE_ROOTS["adsb"])
    by_clause = clause_claims(passed, skipped, prose, ADSB_COMPONENT)
    verify_clauses(by_clause, set(clauses))
    lines = [ADSB_HEADER.format(
        version=quoted(version_h, "kVersion"),
        clauses=len(clauses),
        passed=len(passed),
        skipped=len(skipped),
        kinds=kind_counts(message for _, _, message in skipped) or "none",
    )]
    sections = defaultdict(list)
    for clause, title in clauses.items():
        sections[do260b_section(clause)].append((clause, title))
    for section, entries in sections.items():
        lines.append(f"## {section}\n")
        for clause, title in entries:
            lines.append(f"### {clause} {title}\n")
            lines.extend(by_clause[clause])
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def do260b_section(clause):
    number = clause.split(" ", 1)[1].split(".", 1)[0]
    return f"Section {number}" if number.isdigit() else f"Appendix {number}"


def do260b_clauses(listing):
    clauses, malformed = check_clauses.listed(dataclasses.replace(DO260B, listing=listing))
    if malformed:
        raise ValueError("not a DO-260B clause line:\n" + "\n".join(malformed))
    return clauses


def clause_claims(passed, skipped, prose, component):
    def device_case(case):
        return not case[0].startswith(component)

    claims = defaultdict(list)
    for path, name in sorted(passed, key=device_case):
        claims[subject_of(name)].append(passed_line(path, name, prose))
    for path, name, message in sorted(skipped, key=device_case):
        claims[subject_of(name)].append(skipped_line(path, name, message))
    return claims


def verify_case_paths(cases, roots):
    unknown = sorted({path for path, *_ in cases if not path.startswith(roots)})
    if unknown:
        raise ValueError(f"cases with no place in the report: {', '.join(unknown)}")


def verify_clauses(claims, clauses, optional=()):
    unknown = claims.keys() - clauses - set(optional)
    if unknown:
        raise ValueError(f"cases name no clause of the specification: {', '.join(sorted(unknown))}")
    missing = clauses - claims.keys()
    if missing:
        raise ValueError(f"no case reads {', '.join(sorted(missing))}")


def passed_line(path, name, prose):
    line = f"- {claim_of(name)} (`{path}`)"
    note = prose[path].get(name)
    return f"{line}\n  > {note}" if note else line


def skipped_line(path, name, message):
    return f"- {claim_of(name)} (`{path}`)\n  > Skipped, {message}"


def spec_sections(spec):
    """The SUBPART and APPENDIX sections in order, each with its clauses and their titles."""
    sections, titles = [], {}
    for line in spec.splitlines():
        section = SECTION.match(line)
        if section:
            sections.append((ascii_dashes(section.group(1)), []))
            continue
        heading = CLAUSE_HEADING.match(line)
        if not heading or not sections:
            continue
        clause, title = heading.groups()
        if clause in titles:
            titles[clause].append(title)
        else:
            titles[clause] = [title]
            sections[-1][1].append((clause, titles[clause]))
    return [(name, entries) for name, entries in sections
            if entries or name == PERFORMANCE_APPENDIX]


def en300220_entries(text):
    entries = []
    for line in text.splitlines():
        match = EN300220_CLAUSE.match(line)
        if match:
            entries.append(match.groups())
    return entries


def matching_cases(cases, *roots):
    return [case for case in cases if case[0].startswith(roots)]


def kind_counts(messages):
    counts = Counter(map(check_clauses.kind_of, messages))
    return ", ".join(f"{counts[kind]} {kind}" for kind in check_clauses.KINDS if counts[kind])


def quoted(version_h, name):
    return re.search(rf'{name}\[\] = "([^"]*)"', version_h).group(1)


def subject_of(name):
    return name.split(SEPARATOR, 1)[0]


def claim_of(name):
    return name.split(SEPARATOR, 1)[1]


def ascii_dashes(text):
    return text.replace("\u2013", "-").replace("\u2014", "-")


def read(path):
    with open(path, encoding="utf-8") as source:
        return source.read()


def report(message):
    print(message, file=sys.stderr)


if __name__ == "__main__":
    sys.exit(main())
