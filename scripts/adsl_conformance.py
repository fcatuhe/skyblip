#!/usr/bin/env python3
"""Generate docs/ADSL_CONFORMANCE.md: the ADS-L test report, clause by clause, in spec order.

docs/behavior/ lists every case of the suite by area, so ADS-L's cases sit on four of its
pages: the component's conformance half, the device's half, the stack's unit tests and the
EN 300 220 suite that D.3 names. This report puts them back together for a reader of the
declaration of conformity. Every clause heading of the specification gets its passing cases, from
both halves, and its skipped ones with the reason each was skipped. The EN 300 220 cases follow,
then the stack's own unit tests.

The suite is run twice, through doctest's junit reporter, on the ADS-L and EN 300 220 files alone:
once as CI runs it, which must pass, and once with --no-skip, where a skipped case fails with the
message that says why it is skipped.

    python3 scripts/adsl_conformance.py
"""
import os
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
from collections import defaultdict

import behavior_index
import check_adsl_clauses

ROOT = check_adsl_clauses.ROOT
FIRMWARE = os.path.join(ROOT, "firmware")
TEST_BINARY = os.path.join(FIRMWARE, "build", "skyblip_tests")
OUTPUT = os.path.join(ROOT, "docs", "ADSL_CONFORMANCE.md")
VERSION = os.path.join(FIRMWARE, "protocols", "adsl", "version.h")
EN300220_CLAUSES = os.path.join(FIRMWARE, "test", "en300220", "clauses.txt")

COMPONENT = "protocols/adsl/test/conformance/"
DEVICE = "test/adsl/"
UNIT = "protocols/adsl/test/"
EN300220 = "test/en300220/"
SOURCE_FILES = f"*{UNIT}*,*{DEVICE}*,*{EN300220}*"

APPENDIX = check_adsl_clauses.APPENDIX
PERFORMANCE_APPENDIX = "APPENDIX - PERFORMANCE INFORMATION"
SECTION = re.compile(r"^## ((?:SUBPART|APPENDIX)\b.*)$")
CLAUSE_HEADING = re.compile(rf"^#+\s+({check_adsl_clauses.CLAUSE})\s+(.*)$")
EN300220_CLAUSE = re.compile(r"^(EN 300 220-\d \d+(?:\.\d+)*) (.*)$")
SEPARATOR = behavior_index.SUBJECT_SEPARATOR

HEADER = """# ADS-L conformance

skyBlip's ADS-L implementation {version}, read against {specification} clause by clause by the host test suite. Each of the specification's {clauses} clause headings is below, in the document's order, with the cases that read it: {passed} pass and {skipped} are skipped ({kinds}).

Each claim names the file that checks it, under `firmware/`. A file under `protocols/adsl/test/conformance/` belongs to the component, which builds and passes on its own and goes with any copy of the stack (`firmware/protocols/README.md`, Taking a stack into another project). A file under `test/adsl/` needs skyBlip around the stack, because it checks skyBlip's choices, which a copy replaces with its own. A skipped case is a clause this device makes no claim on, and says why: prose, paperwork, optional, not implemented or unmeasured (`firmware/test/adsl/README.md`). Quoted prose is the comment the case carries.

Generated by `scripts/adsl_conformance.py` from the run itself, and diffed in CI. Do not edit: rename the test case, or rewrite the comment it carries.
"""


def main():
    passed, skipped = run_suite()
    prose = {}
    for path in {path for path, _ in passed} | {path for path, _, _ in skipped}:
        prose[path] = behavior_index.read_prose(path)[1]
    with open(OUTPUT, "w", encoding="utf-8") as out:
        out.write(render(passed, skipped, prose, read(check_adsl_clauses.SPEC),
                         read(EN300220_CLAUSES), read(VERSION)))
    report(f"{len(passed)} cases passed and {len(skipped)} skipped -> "
           f"{os.path.relpath(OUTPUT, ROOT)}")
    return 0


def run_suite():
    if not os.path.exists(TEST_BINARY):
        report(f"no test binary at {os.path.relpath(TEST_BINARY, ROOT)}: run `make test` first")
        sys.exit(1)
    plain = junit()
    if any(failure for _, _, failure in plain):
        report("the ADS-L suite is failing, so it is not a report yet")
        sys.exit(1)
    passed = [(path, name) for path, name, _ in plain]
    ran = set(passed)
    skipped = [(path, name, failure) for path, name, failure in junit("--no-skip")
               if (path, name) not in ran]
    if any(not failure for _, _, failure in skipped):
        report("a skipped case passes with --no-skip: drop its skip")
        sys.exit(1)
    return passed, skipped


# INFO: fc 19nov26 scenario cases open scenarios/*.json by relative path, so this runs in firmware/
def junit(*extra):
    run = subprocess.run(
        [TEST_BINARY, "--reporters=junit", f"--source-file={SOURCE_FILES}", *extra],
        cwd=FIRMWARE, capture_output=True, text=True, encoding="utf-8",
    )
    cases = []
    for case in ET.fromstring(run.stdout).iter("testcase"):
        failure = case.find("failure")
        cases.append((case.get("classname"), case.get("name"),
                      failure.get("message") if failure is not None else None))
    return cases


def render(passed, skipped, prose, spec, en300220_clauses, version_h):
    by_subject = defaultdict(list)
    for path, name in sorted(passed, key=half_of):
        by_subject[subject_of(name)].append(passed_line(path, name, prose))
    for path, name, message in sorted(skipped, key=half_of):
        by_subject[subject_of(name)].append(skipped_line(path, name, message))

    adsl = [(path, name) for path, name in passed if is_adsl_clause_case(path)]
    adsl_skipped = [message for path, _, message in skipped if is_adsl_clause_case(path)]
    sections = spec_sections(spec)
    clauses = {clause for _, entries in sections for clause, _ in entries}
    unknown = {subject_of(name) for path, name in adsl} - clauses - {APPENDIX}
    if unknown:
        report(f"cases name no clause of the specification: {', '.join(sorted(unknown))}")
        sys.exit(1)

    lines = [HEADER.format(
        version=quoted(version_h, "kVersion"),
        specification=quoted(version_h, "kSpecification"),
        clauses=len(clauses),
        passed=len(adsl),
        skipped=len(adsl_skipped),
        kinds=kind_counts(adsl_skipped),
    )]
    for section, entries in sections:
        lines.append(f"## {section}\n")
        for clause, titles in entries:
            lines.append(f"### {clause} {titles[0]}\n")
            for title in titles[1:]:
                lines.append(f"Issue 2 gives the same number to {title}, "
                             "so the cases of both clauses are here.\n")
            lines.extend(by_subject.pop(clause, []))
            lines.append("")
        if section == PERFORMANCE_APPENDIX:
            lines.append(f"### {APPENDIX} Performance information\n")
            lines.extend(by_subject.pop(APPENDIX, []))
            lines.append("")

    lines.append("## EN 300 220, the standard D.3 names\n")
    for clause, title in en300220_entries(en300220_clauses):
        lines.append(f"### {clause} {title}\n")
        lines.extend(by_subject.pop(clause, []))
        lines.append("")

    lines.append("## The stack's own tests\n")
    lines.append("What the component checks beyond the clauses, by file: the packet over a "
                 "bit-error channel, the uplink's code, the media access branch by branch and "
                 "the version.\n")
    unit = defaultdict(list)
    for path, name in passed:
        if path.startswith(UNIT) and not path.startswith(COMPONENT):
            unit[path].append(name)
    for path in sorted(unit):
        lines.append(f"### {path}\n")
        lines.extend(behavior_index.render_subjects(unit[path], prose[path]))
    return "\n".join(lines).rstrip() + "\n"


def passed_line(path, name, prose):
    line = f"- {claim_of(name)} (`{path}`)"
    note = prose[path].get(name)
    return f"{line}\n  > {note}" if note else line


def skipped_line(path, name, message):
    return f"- {claim_of(name)} (`{path}`)\n  > Skipped, {message}"


def spec_sections(spec):
    """The SUBPART and APPENDIX sections in order, each with its clauses and their titles."""
    sections, titles = [], {}
    for line in spec.splitlines():
        section = SECTION.match(line)
        if section:
            sections.append((ascii_dashes(section.group(1)), []))
            continue
        heading = CLAUSE_HEADING.match(line)
        if not heading or not sections:
            continue
        clause, title = heading.groups()
        if clause in titles:
            titles[clause].append(title)
        else:
            titles[clause] = [title]
            sections[-1][1].append((clause, titles[clause]))
    return [(name, entries) for name, entries in sections
            if entries or name == PERFORMANCE_APPENDIX]


def en300220_entries(text):
    entries = []
    for line in text.splitlines():
        match = EN300220_CLAUSE.match(line)
        if match:
            entries.append(match.groups())
    return entries


def half_of(case):
    return 0 if case[0].startswith(COMPONENT) else 1


def is_adsl_clause_case(path):
    return path.startswith(COMPONENT) or path.startswith(DEVICE)


def kind_counts(messages):
    counts = [(sum(check_adsl_clauses.kind_of(message) == kind for message in messages), kind)
              for kind in check_adsl_clauses.KINDS]
    return ", ".join(f"{count} {kind}" for count, kind in counts if count)


def quoted(version_h, name):
    return re.search(rf'{name}\[\] = "([^"]*)"', version_h).group(1)


def subject_of(name):
    return name.split(SEPARATOR, 1)[0]


def claim_of(name):
    return name.split(SEPARATOR, 1)[1]


def ascii_dashes(text):
    return text.replace("\u2013", "-").replace("\u2014", "-")


def read(path):
    with open(path, encoding="utf-8") as source:
        return source.read()


def report(message):
    print(message, file=sys.stderr)


if __name__ == "__main__":
    sys.exit(main())
