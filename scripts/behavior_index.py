#!/usr/bin/env python3
"""Generate docs/BEHAVIOR.md and docs/behavior/: what the host suite says the firmware does.

Nothing here is authored twice. Four things already in the tree are collected:

  the case name        `TEST_CASE("button: a stable press emits exactly one event")`
  the subject          the `button` half of that name, which groups the cases
  the tier             `* doctest::test_suite("main")` on the case, or nothing
  the prose            the comment heading a test file, or heading one case

doctest's xml reporter gives each case's name, file, line and test suite, so the suite
is run rather than listed, and only cases that actually ran are documented. The run nests
each case in a TestSuite element, and opens a new one each time the suite changes in run
order, so a case's tier is the name of the element around it. An unnamed suite has no name
attribute, and a skipped case is reported with skipped="true". The prose is read back out of
the sources.

docs/behavior/ has one page per area of the tree: its main claims, then the others
folded, then its test files. docs/BEHAVIOR.md is the index: the areas with their counts,
and every main claim.

Four rules are enforced, because a doc generated from a suite is only as good as what
the suite says about itself. Every name must read `subject: what holds`, every test file
must open with a comment saying what it pins down, the only test suite is "main", and a
skipped case is never main. A skipped case claims nothing, so it cannot be a main claim.
"""
import os
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
from collections import defaultdict, namedtuple

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIRMWARE = os.path.join(ROOT, "firmware")
TEST_BINARY = os.path.join(FIRMWARE, "build", "skyblip_tests")
OUTPUT = os.path.join(ROOT, "docs", "BEHAVIOR.md")
PAGES = os.path.join(ROOT, "docs", "behavior")
SUBJECT_SEPARATOR = ": "
MAIN = "main"

AREAS = {
    "adsl": "ads-l - ADS-L 4 SRD-860 issue 2, the device read clause by clause",
    "adsl_edge": "adsl_edge - what a Go sends on ADS-L's frame beyond issue 2",
    "adsb": "ads-b - DO-260B draft 4.2, the device read clause by clause",
    "en300220": "en300220 - EN 300 220-1 and -2, the device read clause by clause",
    "protocols/common": "protocols/common - the wire arithmetic the stacks share",
    "protocols/adsl": "protocols/adsl - the ADS-L stack",
    "protocols/adsl/conformance": "protocols/adsl conformance - ADS-L 4 SRD-860 issue 2, the component read clause by clause",
    "protocols/adsl_edge": "protocols/adsl_edge - the stack for what ADS-L issue 2 leaves out",
    "protocols/adsb": "protocols/adsb - the ADS-B stack",
    "protocols/adsb/conformance": "protocols/adsb conformance - DO-260B draft 4.2, the component read clause by clause",
    "protocols/alptas": "protocols/alptas - the ALP-TAS stack",
    "core": "core - the logic the radio and the screen are built on",
    "ui": "ui - screens, widgets and input",
    "ports": "ports - the roles a product needs filled",
    "hardware": "hardware - one folder per part, driver against model",
    "boards": "boards - one assembly, its parts probed on both platforms",
    "products": "products - a SKU end to end, and the committed scenarios",
}

Case = namedtuple("Case", "path line name suite")

INDEX_HEADER = """# Behavior

{cases} over {subjects} in {files}, as the doctest suite states them, on one page per area under [`docs/behavior/`](behavior). A test name is a claim, and each claim links the line where it is checked. Quoted prose is the comment the test file or the case carries.

A main claim states what the device does when used as intended, which a pilot, a reviewer or a declaration of conformity relies on. Every other claim is an edge case or a detail. This page lists the main claims, area by area, and each area's page lists its main claims first and folds the others below them. [Naming a test case](../firmware/README.md#naming-a-test-case), in `firmware/README.md`, says which case is main and how to mark it.

Generated by `scripts/behavior_index.py` from the run itself, and diffed in CI. Do not edit: rename the test case, mark it, or rewrite the comment it carries.

| Area | Cases | Main |
|---|--:|--:|
"""

PAGE_HEADER = """# {title}

{cases} over {subjects} in {files}, as the doctest suite states them. A test name is a claim, and the link beside it is the line where it is checked. Quoted prose is the comment the test file or the case carries. {tiers}

Generated by `scripts/behavior_index.py` from the run itself, and diffed in CI. Do not edit: rename the test case, mark it, or rewrite the comment it carries. [`docs/BEHAVIOR.md`](../BEHAVIOR.md) lists every area.
"""


def main():
    cases, skipped = run_suite()
    prose = {path: read_prose(path) for path in {case.path for case in cases}}

    refusals = problems(cases, skipped, prose)
    if refusals:
        for message in refusals:
            report(message)
        return 1

    write_docs(render_index(cases, prose), render_pages(cases, prose))
    report(f"{len(cases)} cases -> {os.path.relpath(OUTPUT, ROOT)} and "
           f"{os.path.relpath(PAGES, ROOT)}/")
    return 0


def run_suite():
    if not os.path.exists(TEST_BINARY):
        report(f"no test binary at {os.path.relpath(TEST_BINARY, ROOT)}: run `make test` first")
        sys.exit(1)
    # cwd is firmware/ because the scenario cases open scenarios/*.json by relative path.
    run = subprocess.run(
        [TEST_BINARY, "--reporters=xml"],
        cwd=FIRMWARE,
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    if run.returncode != 0:
        report("the suite is failing, so its names are not documentation yet")
        sys.exit(1)
    return parse_run(run.stdout)


def parse_run(xml):
    cases, skipped = [], []
    for suite in ET.fromstring(xml).iter("TestSuite"):
        for case in suite.findall("TestCase"):
            parsed = Case(case.get("filename"), int(case.get("line")), case.get("name"),
                          suite.get("name", ""))
            if case.get("skipped") == "true":
                skipped.append(parsed)
            else:
                cases.append(parsed)
    return cases, skipped


def problems(cases, skipped, prose):
    messages = []
    for case in cases:
        if SUBJECT_SEPARATOR not in case.name:
            messages.append(f"name must read `subject{SUBJECT_SEPARATOR}what holds`: {case.name}")
    for case in cases + skipped:
        if case.suite not in ("", MAIN):
            messages.append(f"test suite must be \"{MAIN}\" or none, not \"{case.suite}\": "
                            f"{case.name}")
    for case in skipped:
        if is_main(case):
            messages.append("a skipped case claims nothing, so it cannot be main: "
                            f"{case.path}: {case.name}")
    for path in sorted(prose):
        if not prose[path][0]:
            messages.append(f"no opening comment saying what it pins down: {path}")
        if area_of(path) not in AREAS:
            messages.append(f"in no area: {path}: name its area in AREAS")
    return messages


def write_docs(index, pages):
    os.makedirs(PAGES, exist_ok=True)
    for name in os.listdir(PAGES):
        if name.endswith(".md") and name not in pages:
            os.remove(os.path.join(PAGES, name))
    write(OUTPUT, index)
    for name, text in pages.items():
        write(os.path.join(PAGES, name), text)


def render_index(cases, prose):
    by_area = group_by_area(cases)
    lines = [INDEX_HEADER.format(
        cases=counted(len(cases), "host test case"),
        subjects=counted(len({subject_of(case.name) for case in cases}), "subject"),
        files=counted(len(prose), "file"),
    ).rstrip("\n")]
    for area in sorted(by_area):
        area_cases = by_area[area]
        lines.append(f"| [{AREAS[area]}](behavior/{page_of(area)}) | {len(area_cases)} | "
                     f"{sum(is_main(case) for case in area_cases)} |")
    lines.append("")

    if not any(is_main(case) for case in cases):
        lines.append("No case is marked main yet.\n")
    for area in sorted(by_area):
        main = [case for case in by_area[area] if is_main(case)]
        if main:
            lines.append(f"## [{AREAS[area]}](behavior/{page_of(area)})\n")
            lines.extend(render_claims(main, prose, "../firmware/"))
    return "\n".join(lines).rstrip() + "\n"


def render_pages(cases, prose):
    return {page_of(area): render_page(area, area_cases, prose)
            for area, area_cases in group_by_area(cases).items()}


def render_page(area, cases, prose):
    main = [case for case in cases if is_main(case)]
    others = [case for case in cases if not is_main(case)]
    paths = sorted({case.path for case in cases})
    if main:
        tiers = (f"Main claims come first ({len(main)}), and the edge cases and details are "
                 f"folded below them ({len(others)}).")
    else:
        tiers = "No case here is marked main yet, so every claim is listed."

    lines = [PAGE_HEADER.format(
        title=AREAS[area],
        cases=counted(len(cases), "host test case"),
        subjects=counted(len({subject_of(case.name) for case in cases}), "subject"),
        files=counted(len(paths), "file"),
        tiers=tiers,
    )]
    if main:
        lines.append("## Main claims\n")
        lines.extend(render_claims(main, prose, "../../firmware/"))
        lines.append(f"<details><summary>Edge cases and details ({len(others)})</summary>\n")
        lines.extend(render_claims(others, prose, "../../firmware/"))
        lines.append("</details>\n")
    else:
        lines.append("## Claims\n")
        lines.extend(render_claims(others, prose, "../../firmware/"))

    lines.append("## Test files\n")
    for path in paths:
        lines.append(f"### [{path}](../../firmware/{path})\n")
        lines.append(f"{prose[path][0]}\n")
    return "\n".join(lines).rstrip() + "\n"


def render_claims(cases, prose, firmware):
    by_subject = defaultdict(list)
    for case in cases:
        by_subject[subject_of(case.name)].append(case)

    lines = []
    for subject, group in sorted(by_subject.items()):
        lines.append(f"**{subject}**\n")
        for case in sorted(group, key=lambda case: (case.path, case.line)):
            link = f"[{os.path.basename(case.path)}:{case.line}]({firmware}{case.path}#L{case.line})"
            lines.append(f"- {claim_of(case.name)} ({link})")
            note = prose[case.path][1].get(case.name)
            if note:
                lines.append(f"  > {note}")
        lines.append("")
    return lines


def render_subjects(names, notes):
    by_subject = defaultdict(list)
    for name in names:
        by_subject[subject_of(name)].append(name)

    lines = []
    for subject, group in sorted(by_subject.items()):
        lines.append(f"**{subject}**\n")
        for name in sorted(group):
            lines.append(f"- {name.split(SUBJECT_SEPARATOR, 1)[1]}")
            if name in notes:
                lines.append(f"  > {notes[name]}")
        lines.append("")
    return lines


def subject_of(name):
    return name.split(SUBJECT_SEPARATOR, 1)[0]


def claim_of(name):
    return name.split(SUBJECT_SEPARATOR, 1)[1]


def counted(count, noun):
    return f"{count} {noun}" if count == 1 else f"{count} {noun}s"


def is_main(case):
    return case.suite == MAIN


COMMENT_BLOCK = r"(?:[ \t]*//[^\n]*\n)+"
FILE_INTRO = re.compile(rf"\A{COMMENT_BLOCK}")
CASE_NOTE = re.compile(rf"^({COMMENT_BLOCK})TEST_CASE\(\s*\"((?:[^\"\\]|\\.)*)\"", re.M)


def read_prose(path):
    """The file's opening comment, and the comment heading each documented case."""
    with open(os.path.join(FIRMWARE, path), encoding="utf-8") as source:
        text = source.read()
    intro = FILE_INTRO.match(text)
    notes = {
        unescape(match.group(2)): flatten(match.group(1)) for match in CASE_NOTE.finditer(text)
    }
    return flatten(intro.group()) if intro else "", notes


def unescape(literal):
    return literal.replace('\\"', '"').replace("\\\\", "\\")


def flatten(comment):
    return " ".join(line.strip().lstrip("/").strip() for line in comment.strip().splitlines())


def group_by_area(cases):
    areas = defaultdict(list)
    for case in cases:
        areas[area_of(case.path)].append(case)
    return areas


def area_of(path):
    parts = path.split("/")
    if parts[0] == "protocols":
        return "/".join(parts[:2] + parts[3:-1])
    return parts[1] if len(parts) > 2 else ""


def page_of(area):
    return re.sub(r"[/_]", "-", area) + ".md"


def write(path, text):
    with open(path, "w", encoding="utf-8") as out:
        out.write(text)


def report(message):
    print(message, file=sys.stderr)


if __name__ == "__main__":
    sys.exit(main())
